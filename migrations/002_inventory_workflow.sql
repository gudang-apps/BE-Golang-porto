BEGIN;

CREATE TABLE IF NOT EXISTS web_db.inventory_scans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode varchar(160) NOT NULL,
    quantity integer NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 10000),
    user_id bigint NOT NULL REFERENCES users.users(id) ON DELETE RESTRICT,
    scanned_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS inventory_scans_user_time_idx
    ON web_db.inventory_scans (user_id, scanned_at DESC);
CREATE INDEX IF NOT EXISTS inventory_scans_barcode_time_idx
    ON web_db.inventory_scans (barcode, scanned_at DESC);

CREATE TABLE IF NOT EXISTS web_db.sku_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku varchar(100) NOT NULL,
    name varchar(200) NOT NULL,
    cost_price bigint NOT NULL DEFAULT 0 CHECK (cost_price >= 0),
    sell_price bigint NOT NULL DEFAULT 0 CHECK (sell_price >= 0),
    stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
    notes text NOT NULL DEFAULT '',
    photo text NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    submitted_by bigint NOT NULL REFERENCES users.users(id) ON DELETE RESTRICT,
    reviewed_by bigint REFERENCES users.users(id) ON DELETE RESTRICT,
    review_note varchar(1000) NOT NULL DEFAULT '',
    submitted_at timestamptz NOT NULL DEFAULT now(),
    reviewed_at timestamptz,
    CHECK ((status = 'pending' AND reviewed_by IS NULL AND reviewed_at IS NULL)
        OR (status <> 'pending' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS sku_requests_status_time_idx
    ON web_db.sku_requests (status, submitted_at DESC);
CREATE INDEX IF NOT EXISTS sku_requests_submitter_time_idx
    ON web_db.sku_requests (submitted_by, submitted_at DESC);

COMMIT;
