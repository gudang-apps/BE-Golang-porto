BEGIN;

CREATE SCHEMA IF NOT EXISTS users;
CREATE SCHEMA IF NOT EXISTS web_db;
CREATE SCHEMA IF NOT EXISTS mobile_db;

CREATE TABLE IF NOT EXISTS users.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL,
    email varchar(254) NOT NULL UNIQUE CHECK (email = lower(email)),
    password_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users.roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(40) NOT NULL UNIQUE CHECK (name IN ('owner', 'staff'))
);

CREATE TABLE IF NOT EXISTS users.user_has_roles (
    user_id bigint NOT NULL REFERENCES users.users(id) ON DELETE CASCADE,
    role_id bigint NOT NULL REFERENCES users.roles(id) ON DELETE RESTRICT,
    PRIMARY KEY (user_id, role_id)
);

INSERT INTO users.roles (name)
VALUES ('owner'), ('staff')
ON CONFLICT (name) DO NOTHING;

CREATE TABLE IF NOT EXISTS web_db.products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku varchar(100) NOT NULL UNIQUE,
    name varchar(200) NOT NULL,
    cost_price bigint NOT NULL CHECK (cost_price >= 0),
    sell_price bigint NOT NULL CHECK (sell_price >= 0),
    stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
    status varchar(20) NOT NULL DEFAULT 'Ready'
        CHECK (status IN ('Ready', 'Sold', 'Rusak', 'Retur')),
    notes text NOT NULL DEFAULT '',
    created_by bigint NOT NULL REFERENCES users.users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS products_name_search_idx ON web_db.products (lower(name));

CREATE TABLE IF NOT EXISTS web_db.product_photos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES web_db.products(id) ON DELETE CASCADE,
    url text NOT NULL,
    sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0)
);
CREATE INDEX IF NOT EXISTS product_photos_product_order_idx
    ON web_db.product_photos (product_id, sort_order);

CREATE TABLE IF NOT EXISTS web_db.sales (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES web_db.products(id) ON DELETE RESTRICT,
    user_id bigint NOT NULL REFERENCES users.users(id) ON DELETE RESTRICT,
    platform varchar(30) NOT NULL
        CHECK (platform IN ('Instagram', 'WhatsApp', 'Shopee', 'Tokopedia', 'Offline', 'Lainnya')),
    qty integer NOT NULL CHECK (qty > 0),
    final_price bigint NOT NULL CHECK (final_price >= 0),
    extra_cost bigint NOT NULL DEFAULT 0 CHECK (extra_cost >= 0),
    total_modal bigint NOT NULL CHECK (total_modal >= 0),
    omzet bigint NOT NULL CHECK (omzet >= 0),
    profit bigint NOT NULL,
    sold_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sales_sold_at_idx ON web_db.sales (sold_at DESC);
CREATE INDEX IF NOT EXISTS sales_product_idx ON web_db.sales (product_id);
CREATE INDEX IF NOT EXISTS sales_user_idx ON web_db.sales (user_id);

CREATE TABLE IF NOT EXISTS web_db.stock_movements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES web_db.products(id) ON DELETE RESTRICT,
    sale_id bigint REFERENCES web_db.sales(id) ON DELETE SET NULL,
    user_id bigint NOT NULL REFERENCES users.users(id) ON DELETE RESTRICT,
    type varchar(20) NOT NULL CHECK (type IN ('sale', 'adjust', 'damaged', 'return')),
    qty_change integer NOT NULL CHECK (qty_change <> 0),
    note text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((type = 'sale' AND sale_id IS NOT NULL) OR (type <> 'sale' AND sale_id IS NULL))
);
CREATE INDEX IF NOT EXISTS stock_movements_product_time_idx
    ON web_db.stock_movements (product_id, created_at DESC);
CREATE INDEX IF NOT EXISTS stock_movements_sale_idx ON web_db.stock_movements (sale_id);

CREATE TABLE IF NOT EXISTS mobile_db.devices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users.users(id) ON DELETE CASCADE,
    name varchar(150) NOT NULL,
    platform varchar(20) NOT NULL CHECK (platform IN ('desktop', 'android')),
    push_token text UNIQUE,
    last_active_at timestamptz
);
CREATE INDEX IF NOT EXISTS devices_user_idx ON mobile_db.devices (user_id);

COMMIT;
